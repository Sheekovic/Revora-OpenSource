BEGIN;
SET LOCAL ROLE revora_migrator;

CREATE TABLE game.item_instances (
    item_instance_id uuid PRIMARY KEY,
    legacy_item_uid integer GENERATED BY DEFAULT AS IDENTITY UNIQUE CHECK (legacy_item_uid > 0),
    owner_character_id uuid NOT NULL REFERENCES game.characters(character_id) ON DELETE CASCADE,
    item_source_id uuid NOT NULL,
    item_type bigint NOT NULL,
    stack_count integer NOT NULL DEFAULT 1 CHECK (stack_count BETWEEN 1 AND 65535),
    durability integer NOT NULL DEFAULT 0 CHECK (durability BETWEEN 0 AND 65535),
    maximum_durability integer NOT NULL DEFAULT 0 CHECK (maximum_durability BETWEEN 0 AND 65535),
    plus smallint NOT NULL DEFAULT 0 CHECK (plus BETWEEN 0 AND 12),
    bless smallint NOT NULL DEFAULT 0 CHECK (bless BETWEEN 0 AND 7),
    enchant integer NOT NULL DEFAULT 0 CHECK (enchant BETWEEN 0 AND 255),
    socket_one integer NOT NULL DEFAULT 0 CHECK (socket_one BETWEEN 0 AND 255),
    socket_two integer NOT NULL DEFAULT 0 CHECK (socket_two BETWEEN 0 AND 255),
    color integer NOT NULL DEFAULT 0 CHECK (color BETWEEN 0 AND 255),
    bound boolean NOT NULL DEFAULT false,
    locked_until timestamptz NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    row_version bigint NOT NULL DEFAULT 1 CHECK (row_version > 0),
    UNIQUE (item_instance_id, owner_character_id),
    UNIQUE (item_instance_id, owner_character_id, item_source_id, item_type),
    FOREIGN KEY (item_source_id, item_type)
        REFERENCES gameplay_reference.item_types(source_id, item_type),
    CHECK (durability <= maximum_durability OR maximum_durability = 0)
);

CREATE TABLE game.inventory_profiles (
    character_id uuid PRIMARY KEY REFERENCES game.characters(character_id) ON DELETE CASCADE,
    slot_capacity smallint NOT NULL DEFAULT 40 CHECK (slot_capacity BETWEEN 1 AND 255),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    row_version bigint NOT NULL DEFAULT 1 CHECK (row_version > 0)
);

CREATE TABLE game.item_locations (
    item_instance_id uuid PRIMARY KEY,
    owner_character_id uuid NOT NULL,
    location_kind text NOT NULL CHECK (location_kind IN ('inventory', 'equipment', 'trade', 'personal-shop')),
    slot smallint NOT NULL CHECK (slot BETWEEN 0 AND 255),
    placed_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    row_version bigint NOT NULL DEFAULT 1 CHECK (row_version > 0),
    FOREIGN KEY (item_instance_id, owner_character_id)
        REFERENCES game.item_instances(item_instance_id, owner_character_id) ON DELETE CASCADE,
    UNIQUE (owner_character_id, location_kind, slot),
    CHECK ((location_kind = 'equipment' AND slot BETWEEN 1 AND 32) OR
           (location_kind <> 'equipment'))
);

CREATE TABLE game.gameplay_command_receipts (
    command_id uuid PRIMARY KEY,
    fingerprint text NOT NULL CHECK (
        length(fingerprint) BETWEEN 1 AND 512 AND
        fingerprint !~ '[[:cntrl:]]'),
    result_code integer NOT NULL CHECK (result_code BETWEEN 0 AND 255),
    result_item_instance_id uuid NULL,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX item_instances_owner_type_idx
    ON game.item_instances(owner_character_id, item_type, legacy_item_uid);
CREATE INDEX item_locations_owner_kind_idx
    ON game.item_locations(owner_character_id, location_kind, slot);

GRANT SELECT, INSERT, UPDATE, DELETE ON game.item_instances,
    game.inventory_profiles, game.item_locations TO revora_game;
GRANT SELECT, INSERT ON game.gameplay_command_receipts TO revora_game;
GRANT USAGE, SELECT ON SEQUENCE game.item_instances_legacy_item_uid_seq TO revora_game;
GRANT SELECT ON game.item_instances, game.inventory_profiles, game.item_locations,
    game.gameplay_command_receipts TO revora_backup;
GRANT SELECT ON SEQUENCE game.item_instances_legacy_item_uid_seq TO revora_backup;

COMMIT;
