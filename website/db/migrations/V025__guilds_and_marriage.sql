BEGIN;
SET LOCAL ROLE revora_migrator;

CREATE TABLE game.guilds (
    guild_id uuid PRIMARY KEY,
    legacy_guild_uid integer GENERATED BY DEFAULT AS IDENTITY UNIQUE CHECK (legacy_guild_uid > 0),
    realm_id uuid NOT NULL REFERENCES game.realms(realm_id) ON DELETE RESTRICT,
    name text NOT NULL CHECK (length(name) BETWEEN 1 AND 16 AND name !~ '[[:cntrl:]]'),
    leader_character_id uuid NOT NULL REFERENCES game.characters(character_id) ON DELETE RESTRICT,
    silver_fund bigint NOT NULL DEFAULT 0 CHECK (silver_fund >= 0),
    bulletin text NOT NULL DEFAULT '' CHECK (length(bulletin) <= 255 AND bulletin !~ '[[:cntrl:]]'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    row_version bigint NOT NULL DEFAULT 1 CHECK (row_version > 0),
    UNIQUE (realm_id, leader_character_id)
);
CREATE UNIQUE INDEX guilds_name_ci_uq ON game.guilds(realm_id, lower(name));

CREATE TABLE game.guild_members (
    guild_id uuid NOT NULL REFERENCES game.guilds(guild_id) ON DELETE CASCADE,
    character_id uuid NOT NULL UNIQUE REFERENCES game.characters(character_id) ON DELETE CASCADE,
    rank text NOT NULL CHECK (rank IN ('leader', 'deputy', 'member')),
    donation bigint NOT NULL DEFAULT 0 CHECK (donation >= 0),
    joined_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (guild_id, character_id)
);

CREATE TABLE game.marriages (
    marriage_id uuid PRIMARY KEY,
    first_character_id uuid NOT NULL REFERENCES game.characters(character_id) ON DELETE RESTRICT,
    second_character_id uuid NOT NULL REFERENCES game.characters(character_id) ON DELETE RESTRICT,
    married_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    dissolved_at timestamptz NULL,
    row_version bigint NOT NULL DEFAULT 1 CHECK (row_version > 0),
    CHECK (first_character_id <> second_character_id)
);
CREATE UNIQUE INDEX marriages_active_first_uq ON game.marriages(first_character_id) WHERE dissolved_at IS NULL;
CREATE UNIQUE INDEX marriages_active_second_uq ON game.marriages(second_character_id) WHERE dissolved_at IS NULL;

GRANT SELECT, INSERT, UPDATE, DELETE ON game.guilds, game.guild_members,
    game.marriages TO revora_game;
GRANT USAGE, SELECT ON SEQUENCE game.guilds_legacy_guild_uid_seq TO revora_game;
GRANT SELECT ON game.guilds, game.guild_members, game.marriages TO revora_backup;
GRANT SELECT ON SEQUENCE game.guilds_legacy_guild_uid_seq TO revora_backup;

COMMIT;
