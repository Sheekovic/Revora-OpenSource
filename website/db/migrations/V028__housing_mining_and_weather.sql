BEGIN;
SET LOCAL ROLE revora_migrator;

CREATE TABLE gameplay_reference.furniture_definitions (
    source_id uuid NOT NULL REFERENCES gameplay_reference.import_sources(source_id),
    furniture_type bigint NOT NULL CHECK (furniture_type > 0),
    mesh bigint NOT NULL CHECK (mesh > 0),
    footprint_width smallint NOT NULL DEFAULT 1 CHECK (footprint_width BETWEEN 1 AND 32),
    footprint_height smallint NOT NULL DEFAULT 1 CHECK (footprint_height BETWEEN 1 AND 32),
    canonical_record_sha256 text NOT NULL CHECK (canonical_record_sha256 ~ '^[0-9a-f]{64}$'),
    PRIMARY KEY (source_id, furniture_type)
);

CREATE TABLE gameplay_reference.mining_nodes (
    source_id uuid NOT NULL REFERENCES gameplay_reference.import_sources(source_id),
    mining_node_id bigint NOT NULL CHECK (mining_node_id > 0),
    map_source_id uuid NOT NULL,
    map_id integer NOT NULL,
    minimum_x integer NOT NULL CHECK (minimum_x BETWEEN 0 AND 65535),
    minimum_y integer NOT NULL CHECK (minimum_y BETWEEN 0 AND 65535),
    maximum_x integer NOT NULL CHECK (maximum_x BETWEEN minimum_x AND 65535),
    maximum_y integer NOT NULL CHECK (maximum_y BETWEEN minimum_y AND 65535),
    enabled boolean NOT NULL DEFAULT false,
    canonical_record_sha256 text NOT NULL CHECK (canonical_record_sha256 ~ '^[0-9a-f]{64}$'),
    PRIMARY KEY (source_id, mining_node_id),
    FOREIGN KEY (map_source_id, map_id)
        REFERENCES gameplay_reference.maps(source_id, legacy_map_id)
);

CREATE TABLE gameplay_reference.weather_profiles (
    source_id uuid NOT NULL REFERENCES gameplay_reference.import_sources(source_id),
    map_source_id uuid NOT NULL,
    map_id integer NOT NULL,
    weather_kind text NOT NULL CHECK (weather_kind IN ('clear', 'rain', 'snow', 'leaves')),
    intensity smallint NOT NULL CHECK (intensity BETWEEN 0 AND 255),
    enabled boolean NOT NULL DEFAULT false,
    PRIMARY KEY (source_id, map_id, weather_kind),
    FOREIGN KEY (map_source_id, map_id)
        REFERENCES gameplay_reference.maps(source_id, legacy_map_id)
);

CREATE TABLE game.character_houses (
    house_id uuid PRIMARY KEY,
    owner_character_id uuid NOT NULL UNIQUE REFERENCES game.characters(character_id) ON DELETE CASCADE,
    map_id integer NOT NULL CHECK (map_id > 0),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    row_version bigint NOT NULL DEFAULT 1 CHECK (row_version > 0)
);

CREATE TABLE game.house_furniture (
    house_id uuid NOT NULL REFERENCES game.character_houses(house_id) ON DELETE CASCADE,
    furniture_uid integer GENERATED BY DEFAULT AS IDENTITY,
    furniture_source_id uuid NOT NULL,
    furniture_type bigint NOT NULL,
    x integer NOT NULL CHECK (x BETWEEN 0 AND 65535),
    y integer NOT NULL CHECK (y BETWEEN 0 AND 65535),
    direction smallint NOT NULL CHECK (direction BETWEEN 0 AND 7),
    PRIMARY KEY (house_id, furniture_uid),
    FOREIGN KEY (furniture_source_id, furniture_type)
        REFERENCES gameplay_reference.furniture_definitions(source_id, furniture_type)
);

GRANT SELECT ON gameplay_reference.furniture_definitions,
    gameplay_reference.mining_nodes, gameplay_reference.weather_profiles TO revora_game, revora_backup;
GRANT SELECT, INSERT, UPDATE, DELETE ON game.character_houses, game.house_furniture TO revora_game;
GRANT USAGE, SELECT ON SEQUENCE game.house_furniture_furniture_uid_seq TO revora_game;
GRANT SELECT ON game.character_houses, game.house_furniture TO revora_backup;
GRANT SELECT ON SEQUENCE game.house_furniture_furniture_uid_seq TO revora_backup;

COMMIT;
